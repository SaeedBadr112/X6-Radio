const mapFr = GENRE_TRANSLATIONS.fr;

function translateGenre(genre) {
    if (!genre) return t('genre_variety');
    const lang = currentLanguage || 'en';
    if (lang === 'ar') return genre;
    const candidates = [genre];
    const withoutAl = genre.replace(/^(ال)/, '');
    if (withoutAl !== genre) candidates.push(withoutAl);
    let englishGenre = null;
    for (const cand of candidates) {
        if (mapEn[cand]) { englishGenre = mapEn[cand]; break; }
    }
    if (lang === 'en') return englishGenre || genre;
    let targetMap = null;
    if (lang === 'fr') targetMap = mapFr;
    else if (lang === 'es') targetMap = mapEs;
    else if (lang === 'de') targetMap = mapDe;
    else if (lang === 'pt') targetMap = mapPt;
    if (targetMap && englishGenre && targetMap[englishGenre]) {
        return targetMap[englishGenre];
    }
    return englishGenre || genre;
}

window.translateGenre = translateGenre;